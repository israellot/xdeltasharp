using System.Security.Cryptography;
using XDeltaSharp.Blake3;
using XDeltaSharp.Lzma;

namespace XDeltaSharp.Benchmarks;

internal static class DecoderBenchmarks
{
    internal static void Run()
    {
        Console.WriteLine("Case,Source B,Target B,Patch B,API,ns/op,Allocated B/op");
        byte[] literal = "literal"u8.ToArray();
        byte[] literalPatch = Vcdiff.Encode([], literal);
        byte[] literalDigest = SHA256.HashData(literal);
        MeasureCase("single ADD", [], literalPatch, literal.Length, literalDigest);
        MeasureCase("single ADD via LZMA", [], literalPatch, literal.Length, literalDigest, lzma: true);

        string fixtures = Path.Combine(AppContext.BaseDirectory, "Fixtures");
        byte[] source = File.ReadAllBytes(Path.Combine(fixtures, "source.txt"));
        byte[] target = File.ReadAllBytes(Path.Combine(fixtures, "target.txt"));
        byte[] patch = File.ReadAllBytes(Path.Combine(fixtures, "xdelta3-checksum.vcdiff"));
        byte[] targetDigest = SHA256.HashData(target);
        MeasureCase("xdelta3 checksum", source, patch, target.Length, targetDigest);
        MeasureCase("raw checksum via LZMA", source, patch, target.Length, targetDigest, lzma: true);

        // Length and digest of multi.bin as generated by the independent fixture recipe in Fixtures/README.md.
        const int multiWindowLength = 16_779_027;
        byte[] digest = Convert.FromHexString("BDF1101EA6B7190EBC217CD0782B82320298238FE59E2D0C1B49F38B8F9CDE73");
        byte[] compressed = File.ReadAllBytes(Path.Combine(fixtures, "xdelta3-lzma.vcdiff"));
        MeasureCase("xdelta3 LZMA", source, compressed, multiWindowLength, digest, lzma: true);
        MeasureCase("xdelta3 LZMA + BLAKE3", source, compressed, multiWindowLength, digest, lzma: true,
            armor: Blake3Armor.Verify);
    }

    private static void MeasureCase(string name, byte[] source, byte[] patch, int targetLength, byte[] digest,
        bool lzma = false, VcdiffArmor armor = default)
    {
        byte[] array = [];
        Measure("array", () => array = lzma
            ? LzmaVcdiff.Decode(source, patch, armor, maxOutputBytes: targetLength)
            : Vcdiff.Decode(source, patch, maxOutputBytes: targetLength));
        Validate(array);

        byte[] buffer = new byte[targetLength];
        int written = 0;
        Measure("span", () => written = lzma
            ? LzmaVcdiff.Decode(source, patch, buffer.AsSpan(), armor)
            : Vcdiff.Decode(source, patch, buffer.AsSpan()));
        Validate(buffer.AsSpan(0, written));

        using var dictionary = new MemoryStream(source, writable: false);
        using var input = new MemoryStream(patch, writable: false);
        using var output = new MemoryStream(targetLength);
        long streamed = 0;
        Measure("stream", () =>
        {
            dictionary.Position = 0;
            input.Position = 0;
            output.SetLength(0);
            streamed = lzma
                ? LzmaVcdiff.Decode(dictionary, input, output, armor, maxOutputBytes: targetLength)
                : Vcdiff.Decode(dictionary, input, output, maxOutputBytes: targetLength);
        });
        if (streamed != output.Length)
            throw new InvalidDataException($"Incorrect stream length for {name}.");
        Validate(output.GetBuffer().AsSpan(0, (int)streamed));

        void Measure(string api, Action decode)
        {
            var (nanoseconds, allocated) = BenchmarkTimer.Measure(decode, warmupMilliseconds: 250);
            Console.WriteLine(FormattableString.Invariant(
                $"{name},{source.Length},{targetLength},{patch.Length},{api},{nanoseconds:F1},{allocated:F1}"));
        }

        void Validate(ReadOnlySpan<byte> bytes)
        {
            if (bytes.Length != targetLength || !SHA256.HashData(bytes).AsSpan().SequenceEqual(digest))
                throw new InvalidDataException($"Incorrect decoder output for {name}.");
        }
    }
}
